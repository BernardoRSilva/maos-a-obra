CREATE TABLE IF NOT EXISTS volunteers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(50) UNIQUE NOT NULL,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('COORDINATOR','VOLUNTEER')),
 name VARCHAR(150) NOT NULL,
 birth_date DATE NOT NULL,
 phone VARCHAR(30) NOT NULL,
 skills VARCHAR(250) NOT NULL DEFAULT '',
 availability VARCHAR(150) NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS shifts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(160) NOT NULL,
 starts_at TIMESTAMP NOT NULL,
 ends_at TIMESTAMP NOT NULL,
 place VARCHAR(160) NOT NULL,
 capacity INT NOT NULL CHECK(capacity > 0),
 required_skill VARCHAR(100) NOT NULL DEFAULT '',
 -- ALL: everyone needs the skill; ONE: at least one confirmed enrollee has skill
 skill_policy VARCHAR(10) NOT NULL DEFAULT 'ALL' CHECK(skill_policy IN ('ALL','ONE')),
 CHECK(ends_at > starts_at)
);
CREATE TABLE IF NOT EXISTS enrollments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shift_id BIGINT NOT NULL REFERENCES shifts(id) ON DELETE CASCADE,
 volunteer_id BIGINT NOT NULL REFERENCES volunteers(id) ON DELETE CASCADE,
 status VARCHAR(20) NOT NULL DEFAULT 'REGISTERED' CHECK(status IN ('REGISTERED','PRESENT','ABSENT','CANCELLED')),
 UNIQUE(shift_id,volunteer_id)
);
CREATE TABLE IF NOT EXISTS historical_attendance (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 volunteer_id BIGINT NOT NULL REFERENCES volunteers(id),
 action_name VARCHAR(150) NOT NULL,
 occurred_on DATE NOT NULL,
 hours NUMERIC(6,2) NOT NULL CHECK(hours >= 0),
 present BOOLEAN NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_enrollments_shift ON enrollments(shift_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_volunteer ON enrollments(volunteer_id);
CREATE INDEX IF NOT EXISTS idx_shifts_starts ON shifts(starts_at);
